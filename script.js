function validEndpoint(){
  try{
    const endpoint=new URL(REGISTRATION_ENDPOINT);
    return endpoint.protocol==='https:'&&endpoint.hostname==='script.google.com'&&/^\/macros\/s\/[^/]+\/exec$/.test(endpoint.pathname);
  }catch{return false;}
}
function createRequestId(){
  return window.crypto?.randomUUID?window.crypto.randomUUID():`${Date.now()}-${Math.random().toString(36).slice(2)}`;
}
