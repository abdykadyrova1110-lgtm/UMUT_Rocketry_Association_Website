function formatPhone(value){
  const raw=value.trim();
  const digits=raw.replace(/\D/g,'');
  if(raw.startsWith('+')&&digits.length<3&&'996'.startsWith(digits)) return raw;
  let localDigits=digits;
  if(/^\+996/.test(raw)) localDigits=digits.slice(3);
  else if(digits.startsWith('996')&&digits.length>9) localDigits=digits.slice(3);
  localDigits=localDigits.slice(0,9);
  const groups=[localDigits.slice(0,3),localDigits.slice(3,6),localDigits.slice(6,9)].filter(Boolean);
  return `+996${groups.length?' '+groups.join(' '):''}`;
}
